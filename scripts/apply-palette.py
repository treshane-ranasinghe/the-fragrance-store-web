"""
Re-colours the original thefragrancestore.lk stylesheets with the spec 15 palette
(deep emerald greens + rich metallic gold, built on the spec 15 colours), keeping every rule and class.

  python3 scripts/apply-palette.py <path-to-original-css-folder>

Writes app/styles.css and app/shop.css. Only the colours change; layout and motion are untouched.
Shades that aren't in the six brand colours are derived from them (tints / shades of Gold and Cream).
"""
import re, sys, pathlib

SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else '../thefragrancestore.lk/css')
OUT = pathlib.Path(__file__).resolve().parent.parent / 'app'

ROOT_VARS = {
    '--onyx':       '#0B281F',   # deep emerald — main dark background (richer than Deep Forest)
    '--ink':        '#12352B',   # Deep Forest Green (spec 15) — raised surfaces
    '--char':       '#143A2F',   # between the two — product cards
    '--ivory':      '#F5F0E6',   # Cream / Ivory (spec 15)
    '--parchment':  '#DCCFB8',   # Warm Beige (spec 15)
    '--gold':       '#C6A566',   # rich metallic gold (warmer than Gold / Tan)
    '--gold-light': '#E8D5A8',   # champagne highlight
    '--gold-deep':  '#7D6435',   # Gold Dark (spec 15) — gold text on light sections
    '--amber':      '#C6A566',
    '--text-light': '#F5F0E6',   # Cream on green
    '--text-dim':   '#AFB4AA',   # Cream 70% over the emerald (secondary text)
    '--text-dark':  '#1D2924',   # Dark Text (spec 15)
    '--text-mid':   '#5B6660',   # Muted Text (spec 15)
    '--line-dark':  'rgba(198, 165, 102, 0.24)',
    '--line-light': 'rgba(29, 41, 36, 0.14)',
    '--gold-grad':  'linear-gradient(135deg, #6B5226 0%, #B8913F 18%, #F3E4BB 42%, #C6A566 58%, #EBD8AA 76%, #7D6435 100%)',
}

RGB = {  # hard-coded rgb triplets → brand equivalents (alpha kept)
    (10, 9, 8): (11, 40, 31),        # onyx → deep emerald
    (20, 17, 14): (18, 53, 43),      # ink → Deep Forest
    (40, 30, 15): (22, 60, 46),
    (5, 4, 3): (5, 22, 17),          # modal / bag backdrop
    (201, 164, 92): (198, 165, 102), # champagne → rich gold
    (233, 211, 160): (232, 213, 168),
    (255, 240, 210): (250, 238, 210),
    (245, 239, 230): (245, 240, 230),
    (184, 116, 42): (198, 165, 102), # amber glow → gold
    (26, 23, 20): (29, 41, 36),
}
HEX = {
    '#C9A45C': '#C6A566', '#E9D3A0': '#E8D5A8', '#8F6B2E': '#7D6435', '#F4E4BC': '#F3E4BB',
    '#6E4F1F': '#5F4B27', '#B08A45': '#9A7F45',
    '#0A0908': '#0B281F', '#0B0A09': '#0B281F', '#14110E': '#12352B', '#2A221A': '#1B4A3B', '#0F0D0B': '#0B281F',
    '#000': '#0B281F', '#D9A444': '#C6A566',
}

def recolour(css: str) -> str:
    def rgba(m):
        r, g, b, a = int(m[1]), int(m[2]), int(m[3]), m[4]
        nr, ng, nb = RGB.get((r, g, b), (r, g, b))
        return f'rgba({nr},{ng},{nb},{a})'
    css = re.sub(r'rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([.\d]+)\s*\)', rgba, css)
    for a, b in HEX.items():
        css = re.sub(re.escape(a) + r'(?![0-9A-Fa-f])', b, css, flags=re.I)
    # data-URI SVG strokes (%23C9A45C)
    css = css.replace('%23C9A45C', '%23C6A566')
    return css

def set_root(css: str) -> str:
    for k, v in ROOT_VARS.items():
        css = re.sub(rf'({re.escape(k)}:\s*)[^;]+;', lambda m: f'{m[1]}{v};', css, count=1)
    return css

for name in ('styles.css', 'shop.css'):
    css = (SRC / name).read_text()
    css = recolour(css)
    if name == 'styles.css':
        css = set_root(css)
        css = css.replace('Palette — Onyx & Champagne Gold', 'Palette — deep emerald & rich gold (built on spec 15: Deep Forest, Cream, Warm Beige, Gold Dark, Dark Text)')
    header = f'/* Generated by scripts/apply-palette.py from the original {name} — same rules, deep emerald & rich gold palette. */\n'
    (OUT / name).write_text(header + css)
    print('wrote', OUT / name)
